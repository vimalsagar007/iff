/**
 * Returns localized string for UI
 */
export function t(key: string, lang: LanguageCode): string {
  if (UI_TRANSLATIONS[key] && UI_TRANSLATIONS[key][lang]) {
    return UI_TRANSLATIONS[key][lang];
  }
  if (UI_TRANSLATIONS[key] && UI_TRANSLATIONS[key]['en']) {
    return UI_TRANSLATIONS[key]['en'];
  }
  return key;
}

/**
 * Returns a freedom fighter object with localized text for the specified language
 */
export function getLocalizedFighter(fighter: FreedomFighter, lang: LanguageCode): FreedomFighter {
  if (lang === 'en') return fighter;

  const loc = FIGHTER_LOCALIZATIONS[fighter.id]?.[lang];
  if (!loc) {
    // If specific fighter translation isn't available, check if fighter has built-in translations
    if (fighter.translations?.[lang]) {
      const customLoc = fighter.translations[lang]!;
      return {
        ...fighter,
        name: customLoc.name || fighter.name,
        titleOrEpithet: customLoc.titleOrEpithet || fighter.titleOrEpithet,
        contribution: customLoc.contribution || fighter.contribution,
        bio: customLoc.bio || fighter.bio,
        famousQuote: customLoc.famousQuote || fighter.famousQuote,
      };
    }
    return fighter;
  }

  return {
    ...fighter,
    name: loc.name || fighter.name,
    titleOrEpithet: loc.titleOrEpithet || fighter.titleOrEpithet,
    contribution: loc.contribution || fighter.contribution,
    bio: loc.bio || fighter.bio,
    famousQuote: loc.famousQuote || fighter.famousQuote,
  };
}
